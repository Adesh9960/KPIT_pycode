@app.route("/DID/<int:DID>", methods=["GET"])
def get_DID(DID: int):
    """
    Fetches the value of a specific Data Identifier (DID) via UDS Service 0x22.

    Args:
        DID (int): The 16-bit identifier index parameter requested by the client interface.
    """
    if uds_client is None: 
        return jsonify({
            "status": "error",
            "message": "UDS client not initialized"
        })
    try:
        response = uds_client.readDataByIdentifier(DID)
        return jsonify({
            "status": "success",
            "data": response 
        })
    except UDSError as e:
        print(e)
        return jsonify({
            "status": "error",
            "message": e.message
        })


