class RouteFilter(logging.Filter):
    """
    Custom logging filter used to clean up engine stdout lines.
    
    Suppresses recurring log entries generated by high-frequency background polling 
    on the `/live-data` endpoint, keeping the core system console clear.
    """
    def filter(self, record: logging.LogRecord) -> bool:
        msg = record.getMessage()
        if "GET /live-data" in msg:
            return False
        return True

# Apply the filter directly to the underlying Werkzeug server engine logger
werkzeug_logger = logging.getLogger("werkzeug")
werkzeug_logger.addFilter(RouteFilter())


