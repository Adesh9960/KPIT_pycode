@app.route("/live-data", methods=["GET"])
def live_data():
    """
    Scrapes high-frequency system telemetry parameters.

    Calculates current transport indices such as message processing speeds (frames per second) 
    and updates error metrics before compiling them into a JSON map response.
    """
    stats = listener.get_stats()
    with analytics_lock:
        global start_time_flag
        global prev_count
        
        latest_analytics["error_frames"] = stats.error_frames
        
        # Calculate localized performance metrics: (Current Frames - Past Frames) / Elapsed Seconds
        delta_time = time.monotonic() - start_time_flag
        latest_analytics["message_speed"] = round((stats.rx_frames - prev_count) / delta_time, 2)
        
        # Sync baseline parameters for the next polling cycle
        prev_count = stats.rx_frames
        start_time_flag = time.monotonic()
        
        return jsonify(latest_analytics)


def send_realtime_data(frame):
    """
    Pipes processed asynchronous network data into web thread caches.

    This callback function updates history buffers and current analytics metrics 
    every time the decoder thread extracts a fresh payload frame from the CAN bus.

    Args:
        frame (CANFrame): Normalized network frame object data.
    """
    analytics = build_analytics_packet(frame)

    with analytics_lock:
        update_history(analytics)
        latest_analytics.update(analytics)


@app.route("/history-data", methods=["GET"])
def history_data():
    """Streams the accumulated chronological historical database records compiled during this session."""
    with analytics_lock:
        history_json = json.dumps(
            {key: list(value) for key, value in history.items()},
            indent=4
        )
        return history_json


