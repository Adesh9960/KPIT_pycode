@app.route("/download/<file>")
def download(file: str):
    """
    Coordinates filesystem archiving and dynamic data dumping operations.

    Handles compressed log extractions or coordinates safe local storage dump mappings 
    by invoking high-level diagnostic firmware download tools before passing the files down 
    the response pipeline. Uses resource cleanup handles upon closing the stream.

    Args:
        file (str): Categorized download token ("logger" or "firmware").
    """
    if file == "logger":
        print("sending logger...")
        zip_folder("../data/logger", "../data/all_logs")
        print("zip created!!")
       
        path = os.path.dirname(os.getcwd())
        path = os.path.join(path, 'data', 'all_logs.zip')
        response = send_file(path, as_attachment=True, conditional=False)
        response.direct_passthrough = False
        
        # Async Lifecycle Cleanup Hook: Erase the temporary zip archive once the client finishes downloading it
        @response.call_on_close
        def cleanup():
            try:
                os.remove(path)
                print("Zip deleted.")
            except Exception as e:
                print(f"Cleanup failed: {e}")
        return response
    
    if file == "firmware":
        path = os.path.join(os.path.dirname(os.getcwd()), 'data', 'firmware', 'firmware.bin')
        try:
            # Command the UDS client engine to read firmware blocks sequentially from the flash memory lines
            uds_client.firmwareUpload(path)
            response = send_file(path, as_attachment=True, conditional=False)
            response.direct_passthrough = False

            @response.call_on_close
            def cleanup():
                try:
                    os.remove(path)
                    print("firmware duplicate deleted.")
                except Exception as e:
                    print(f"Cleanup failed: {e}")
            return response
        except UDSError as e:
            print(e)
            return jsonify({
                "status": "error",
                "message": e.message
            })
        except Exception as e:
            print(e)
            return jsonify({
                "status": "error",
                "message": "Could not download firmware"
            })


